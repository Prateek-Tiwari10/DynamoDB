"""Request IDs: made at the client entry point, carried between nodes, used only in logs.

A request ID is taken from the client's ``x-request-id`` metadata or generated by the node that
receives the client call. Inside a node it lives in a ``ContextVar``, so every task started while
handling the request sees it too. Between nodes it travels in gRPC metadata. It is never stored.
"""

import functools
import logging
import uuid
from contextvars import ContextVar
from typing import Literal

import grpc

METADATA_KEY = "x-request-id"
NO_REQUEST = "-"

REQUEST_ID: ContextVar[str] = ContextVar("request_id", default=NO_REQUEST)

logger = logging.getLogger(__name__)


def _from_metadata(metadata) -> str | None:
    """The request ID found in gRPC metadata, or None."""
    for key, value in metadata or ():
        if key == METADATA_KEY and value:
            return value
    return None


def start_request(metadata) -> str:
    """Client entry point: use the client's ID if it sent one, else make a new one."""
    request_id = _from_metadata(metadata) or uuid.uuid4().hex
    REQUEST_ID.set(request_id)
    return request_id


def adopt(metadata) -> None:
    """Node-to-node entry point: take the ID the calling node sent ("-" if none)."""
    REQUEST_ID.set(_from_metadata(metadata) or NO_REQUEST)


def outgoing() -> tuple[tuple[str, str], ...]:
    """Metadata to attach to a call this node makes to another node."""
    request_id = REQUEST_ID.get()
    if request_id == NO_REQUEST:
        return ()
    return ((METADATA_KEY, request_id),)


def rpc_handler(kind: Literal["client", "node"]):
    """Decorator for every gRPC handler of both services.

    - ``client``: start a request ID and return it in trailing metadata, also on errors.
    - ``node``: adopt the ID sent by the calling node.
    - ``NotImplementedError`` becomes UNIMPLEMENTED, any other ``Exception`` becomes INTERNAL.
      ``BaseException`` (for example a cancellation) is not caught.
    """

    def decorate(method):
        @functools.wraps(method)
        async def wrapper(self, request, context):
            metadata = context.invocation_metadata()
            trailing: tuple[tuple[str, str], ...] = ()
            if kind == "client":
                trailing = ((METADATA_KEY, start_request(metadata)),)
                context.set_trailing_metadata(trailing)
            else:
                adopt(metadata)
            name = method.__name__
            try:
                return await method(self, request, context)
            except grpc.aio.AbortError:
                raise  # the handler aborted on purpose
            except NotImplementedError:
                await context.abort(grpc.StatusCode.UNIMPLEMENTED,
                                    f"{name} is not implemented yet", trailing)
            except Exception:
                logger.exception("%s failed", name)
                await context.abort(grpc.StatusCode.INTERNAL, f"{name} failed", trailing)

        return wrapper

    return decorate


class RequestIdFilter(logging.Filter):
    """Adds ``node_id`` and ``request_id`` (first 8 characters) to every log record."""

    def __init__(self, node_id: str) -> None:
        super().__init__()
        self.node_id = node_id

    def filter(self, record: logging.LogRecord) -> bool:
        record.node_id = self.node_id
        record.request_id = REQUEST_ID.get()[:8]
        return True
